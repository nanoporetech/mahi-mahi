def palette(name: str, color_count: int) -> tuple[RGBColor, ...]:
    colors = PALETTES.get(name)
    if colors is None:
        raise ValueError(f"Unknown palette {name!r}")
    if color_count < 0 or color_count > len(colors):
        raise ValueError(f"Palette {name!r} does not contain {color_count} colors")
    return colors[:color_count]
